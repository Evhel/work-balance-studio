function InstructionPage() {
  const { currentUser } = useStore();
  const [role, setRole] = useState<Position>(currentUser?.position ?? "Сотрудник");

  return (
    <div className="max-w-4xl">
      <h1 className="text-2xl font-semibold">Инструкция</h1>
      <p className="mt-1 text-sm text-muted-foreground">
        Вы вошли как {fio(currentUser)} ({currentUser.position}). Ниже — общие правила работы и
        инструкция для выбранной должности.
      </p>

      <div className="mt-4 flex flex-wrap gap-1">
        {POSITIONS.map((p) => (
          <button
            key={p}
            onClick={() => setRole(p)}
            className={`rounded-md border px-3 py-1.5 text-sm ${
              role === p ? "bg-primary text-primary-foreground" : "bg-background hover:bg-accent"
            }`}
          >
            {p}
          </button>
        ))}
      </div>

      <section className="mt-4 rounded-lg border bg-card p-4">
        <h2 className="text-lg font-medium">Инструкция: {role}</h2>
        <ul className="mt-2 list-disc space-y-1 pl-5 text-sm">
          {BY_ROLE[role].map((t) => (
            <li key={t}>{t}</li>
          ))}
        </ul>
      </section>

      <div className="mt-4 space-y-3">
        {COMMON.map((b) => (
          <section key={b.title} className="rounded-lg border bg-card p-4">
            <h2 className="text-base font-medium">{b.title}</h2>
            <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-muted-foreground">
              {b.items.map((i) => (
                <li key={i}>{i}</li>
              ))}
            </ul>
          </section>
        ))}
      </div>
    </div>
  );
}
